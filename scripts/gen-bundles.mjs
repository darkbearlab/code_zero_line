#!/usr/bin/env node
/**
 * Auto-generates src/config/bundles.gen.ts from JSON files in
 *   src/config/{weapons,units,maps,missions}/
 *
 * Adding / removing a JSON file in those directories no longer requires
 * touching loader.ts — just rerun this script (runs automatically on
 * predev / prebuild / pretest / presim).
 *
 * Files starting with `_` (e.g. `_draft.json`) are skipped, so authors can
 * stash work-in-progress without it accidentally entering the bundle.
 */
import { readdirSync, writeFileSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, '..');
const configDir = join(repoRoot, 'src', 'config');

const SECTIONS = [
  {
    dir: 'weapons',
    exportName: 'BUNDLED_WEAPONS',
    typeImport: "import type { Weapon } from '../core/state/GameState';",
    typeName: 'Weapon',
  },
  {
    dir: 'units',
    exportName: 'BUNDLED_TEMPLATES',
    typeImport: "import type { UnitTemplate } from './loader';",
    typeName: 'UnitTemplate',
  },
  {
    dir: 'maps',
    exportName: 'BUNDLED_MAPS',
    typeImport: "import type { MapDef } from '../core/setup/types';",
    typeName: 'MapDef',
  },
  {
    dir: 'missions',
    exportName: 'BUNDLED_MISSIONS',
    typeImport: "import type { MissionDef } from '../missions/types';",
    typeName: 'MissionDef',
  },
];

const slugToVar = (slug, prefix) => {
  const safe = slug.replace(/[^A-Za-z0-9]/g, '_');
  return `${prefix}_${safe}`;
};

const importLines = [];
const exportBlocks = [];

for (const sec of SECTIONS) {
  const sectionDir = join(configDir, sec.dir);
  const files = existsSync(sectionDir)
    ? readdirSync(sectionDir)
        .filter((f) => f.endsWith('.json') && !f.startsWith('_'))
        .sort()
    : [];
  const varNames = [];
  for (const f of files) {
    const slug = f.replace(/\.json$/, '');
    const varName = slugToVar(slug, sec.dir);
    varNames.push(varName);
    importLines.push(`import ${varName} from './${sec.dir}/${f}';`);
  }
  if (varNames.length === 0) {
    exportBlocks.push(
      `export const ${sec.exportName}: ReadonlyArray<${sec.typeName}> = [];`,
    );
  } else {
    exportBlocks.push(
      [
        `export const ${sec.exportName}: ReadonlyArray<${sec.typeName}> = [`,
        ...varNames.map((n) => `  ${n} as unknown as ${sec.typeName},`),
        `];`,
      ].join('\n'),
    );
  }
}

const typeImportLines = SECTIONS.map((s) => s.typeImport);

const out = [
  '// AUTO-GENERATED by scripts/gen-bundles.mjs — do not edit.',
  '// Re-run with `npm run gen-bundles` after adding/removing JSON content.',
  '',
  ...typeImportLines,
  '',
  ...importLines,
  '',
  ...exportBlocks,
  '',
].join('\n');

writeFileSync(join(configDir, 'bundles.gen.ts'), out);
console.log(`gen-bundles: wrote src/config/bundles.gen.ts`);
